/**
 * MÓDULO DE EXPORTACIÓN PDF
 * Renderiza la partitura a PDF usando canvas + jsPDF.
 * En esta fase usamos un renderizado simplificado basado en texto/canvas.
 * Para producción se integraría VexFlow para renderizado de partitura completo.
 */

import { jsPDF } from 'jspdf';
import {
  type HarmonizedMIDI,
  type QuantizedNote,
  MidiEngineError,
} from '../types';

// ============================================================
// CONSTANTES
// ============================================================

const NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];

const PAGE_WIDTH = 210;  // A4 mm
const PAGE_HEIGHT = 297; // A4 mm
const MARGIN = 15;
const STAFF_HEIGHT = 40;
const LINE_SPACING = 8;
const NOTE_SPACING = 12;

// ============================================================
// CLASE EXPORTADORA
// ============================================================

export class PDFExporter {
  /**
   * Exporta el MIDI procesado como PDF (Uint8Array).
   */
  export(harmonized: HarmonizedMIDI): Uint8Array {
    try {
      return this.buildPDF(harmonized);
    } catch (error) {
      throw new MidiEngineError(
        `Error al exportar PDF: ${(error as Error).message}`,
        'export',
        'PDF_EXPORT_ERROR'
      );
    }
  }

  // ============================================================
  // CONSTRUCCIÓN DEL PDF
  // ============================================================

  private buildPDF(harmonized: HarmonizedMIDI): Uint8Array {
    const doc = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4',
    });

    let currentY = MARGIN;

    // Título
    doc.setFontSize(18);
    doc.text('MIDI Engine Output', PAGE_WIDTH / 2, currentY, { align: 'center' });
    currentY += 10;

    // Info de tonalidad
    const keyInfo = harmonized.harmonicAnalysis.key;
    doc.setFontSize(11);
    doc.text(
      `Key: ${keyInfo.key} | Confidence: ${(keyInfo.confidence * 100).toFixed(1)}% | ` +
      `Tempo: ${harmonized.tempo} BPM | ` +
      `Time: ${harmonized.timeSignature.numerator}/${harmonized.timeSignature.denominator}`,
      PAGE_WIDTH / 2, currentY, { align: 'center' }
    );
    currentY += 10;

    // Análisis armónico - progresión de acordes
    doc.setFontSize(12);
    doc.text('Chord Progression:', MARGIN, currentY);
    currentY += 6;

    doc.setFontSize(10);
    const chordSymbols = harmonized.harmonicAnalysis.chords
      .map(c => c.symbol)
      .join(' → ');
    
    // Word wrap para la progresión
    const maxLineWidth = PAGE_WIDTH - 2 * MARGIN;
    const wrappedLines = doc.splitTextToSize(chordSymbols, maxLineWidth);
    for (const line of wrappedLines) {
      if (currentY > PAGE_HEIGHT - MARGIN) {
        doc.addPage();
        currentY = MARGIN;
      }
      doc.text(line, MARGIN, currentY);
      currentY += 5;
    }
    currentY += 8;

    // Sección: Melodía (notas en formato texto)
    currentY = this.renderNoteSection(doc, 'Melody', harmonized.notes.filter(n => n.track >= 0), harmonized, currentY);
    
    // Sección: Armonía
    if (harmonized.harmonyNotes.length > 0) {
      currentY = this.renderNoteSection(doc, 'Harmony', harmonized.harmonyNotes, harmonized, currentY);
    }

    // Sección: Bajo
    if (harmonized.bassNotes.length > 0) {
      currentY = this.renderNoteSection(doc, 'Bass', harmonized.bassNotes, harmonized, currentY);
    }

    // Renderizar pauta simplificada (staff lines) para la melodía
    currentY += 5;
    if (currentY > PAGE_HEIGHT - 80) {
      doc.addPage();
      currentY = MARGIN;
    }
    currentY = this.renderStaffLines(doc, harmonized, currentY);

    // Footer
    const pageCount = doc.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setFontSize(8);
      doc.text(
        `Generated by MIDI Engine | Page ${i}/${pageCount}`,
        PAGE_WIDTH / 2, PAGE_HEIGHT - 8,
        { align: 'center' }
      );
    }

    return new Uint8Array(doc.output('arraybuffer'));
  }

  /**
   * Renderiza una sección de notas en formato texto compacto.
   */
  private renderNoteSection(
    doc: jsPDF,
    title: string,
    notes: QuantizedNote[],
    harmonized: HarmonizedMIDI,
    startY: number
  ): number {
    let y = startY;

    if (y > PAGE_HEIGHT - 40) {
      doc.addPage();
      y = MARGIN;
    }

    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.text(`${title} (${notes.length} notes)`, MARGIN, y);
    y += 6;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);

    // Mostrar las primeras notas en formato compacto
    const maxNotes = 30;
    const displayNotes = notes.slice(0, maxNotes);

    for (const note of displayNotes) {
      if (y > PAGE_HEIGHT - MARGIN) {
        doc.addPage();
        y = MARGIN;
      }

      const noteName = this.midiToNoteName(note.pitch);
      const beat = (note.startTime / harmonized.ticksPerBeat).toFixed(2);
      const dur = (note.duration / harmonized.ticksPerBeat).toFixed(2);

      doc.text(
        `${noteName} | beat: ${beat} | dur: ${dur} | vel: ${note.velocity}`,
        MARGIN, y
      );
      y += 4;
    }

    if (notes.length > maxNotes) {
      doc.text(`... and ${notes.length - maxNotes} more notes`, MARGIN, y);
      y += 4;
    }

    return y + 5;
  }

  /**
   * Renderiza líneas de pauta (staff) simplificadas.
   */
  private renderStaffLines(doc: jsPDF, harmonized: HarmonizedMIDI, startY: number): number {
    let y = startY;

    if (y > PAGE_HEIGHT - 60) {
      doc.addPage();
      y = MARGIN;
    }

    doc.setFontSize(10);
    doc.setFont('helvetica', 'bold');
    doc.text('Staff View (Simplified):', MARGIN, y);
    y += 8;

    // Dibujar 5 líneas de pauta
    const staffStartX = MARGIN;
    const staffEndX = PAGE_WIDTH - MARGIN;

    for (let i = 0; i < 5; i++) {
      const lineY = y + i * LINE_SPACING;
      doc.setDrawColor(100);
      doc.setLineWidth(0.3);
      doc.line(staffStartX, lineY, staffEndX, lineY);
    }

    // Clave de sol simplificada (texto)
    doc.setFontSize(24);
    doc.text('𝄞', staffStartX + 2, y + 32);

    // Dibujar notas como puntos en la pauta
    const melodyNotes = harmonized.notes.filter(n => n.track >= 0).slice(0, 40);
    const ticksPerBeat = harmonized.ticksPerBeat;
    const availableWidth = staffEndX - staffStartX - 20;
    const totalTicks = harmonized.totalTicks || 1;

    for (const note of melodyNotes) {
      const x = staffStartX + 15 + (note.startTime / totalTicks) * availableWidth;
      
      // Mapear pitch a posición vertical en la pauta
      // Rango: C4 (middle C) en la línea del medio
      const staffCenterLine = y + 2 * LINE_SPACING; // Línea del medio (B4)
      const pitchOffset = note.pitch - 71; // B4 = 71
      const noteY = staffCenterLine - (pitchOffset * LINE_SPACING / 2);

      // Dibujar nota
      const noteRadius = 1.5;
      doc.setFillColor('black');
      doc.circle(x, noteY, noteRadius, 'F');
    }

    // Métrica
    doc.setFontSize(10);
    doc.text(`${harmonized.timeSignature.numerator}`, staffStartX + 8, y + 8);
    doc.text(`${harmonized.timeSignature.denominator}`, staffStartX + 8, y + 16);

    return y + 5 * LINE_SPACING + 10;
  }

  /**
   * Convierte un pitch MIDI a nombre de nota.
   */
  private midiToNoteName(pitch: number): string {
    const noteName = NOTE_NAMES[pitch % 12];
    const octave = Math.floor(pitch / 12) - 1;
    return `${noteName}${octave}`;
  }
}
